#!/usr/bin/env python3
"""Embeds SPIR-V files as uint32_t arrays. Usage: embed_spirv.py <out.h> <Name>=<file.spv>..."""
import struct
import sys
from pathlib import Path

out = ['// Generated by tools/embed_spirv.py. Do not edit.', '#pragma once', '#include <cstdint>']
for arg in sys.argv[2:]:
    name, path = arg.split('=', 1)
    data = Path(path).read_bytes()
    words = struct.unpack('<%dI' % (len(data) // 4), data)
    body = ',\n'.join(', '.join('0x%08x' % w for w in words[i:i + 8]) for i in range(0, len(words), 8))
    out.append(f'static const uint32_t {name}[] = {{\n{body}\n}};')
Path(sys.argv[1]).write_text('\n'.join(out) + '\n')
