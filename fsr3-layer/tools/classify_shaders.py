#!/usr/bin/env python3
"""Classifies X-Plane's installed compute shaders by what they bind, not by archive position.

Reads the SPIR-V in the given .xsa archives (ZIP files; nothing is modified) and emits a C++
table of FNV-1a hashes and roles for the layer:
  Easu           - FSR 1 EASU: binds u_input_texture, i_output_texture, u_fsr_data and gathers.
  SsrScene2D     - scene SSR whose gbuffer_pos / gbuffer_vel are 2D images.
  SsrSceneArray  - the same with 2D-array images (one layer per eye).
Multisampled scene SSR and the water SSR variants (water_pos instead of gbuffer_pos) get no role.

Usage: classify_shaders.py <out.h> <archive.xsa>...
"""
import hashlib
import json
import struct
import sys
import zipfile
from pathlib import Path

OP_NAME, OP_DECORATE, OP_TYPE_IMAGE, OP_TYPE_SAMPLED_IMAGE = 5, 71, 25, 27
OP_TYPE_POINTER, OP_VARIABLE, OP_IMAGE_GATHER = 32, 59, 96
DEC_BINDING = 33
DIM_2D = 1


def fnv(data):
    value = 14695981039346656037
    for byte in data:
        value = ((value ^ byte) * 1099511628211) & ((1 << 64) - 1)
    return value


def parse(spirv):
    words = struct.unpack('<%dI' % (len(spirv) // 4), spirv)
    names, bindings, images, sampled, pointers, variables = {}, {}, {}, {}, {}, {}
    gathers = 0
    i = 5
    while i < len(words):
        count, op = words[i] >> 16, words[i] & 0xFFFF
        if count == 0:
            break
        operands = words[i + 1:i + count]
        if op == OP_NAME:
            names[operands[0]] = bytes(struct.pack('<%dI' % (count - 2), *operands[1:])).split(b'\0')[0].decode()
        elif op == OP_DECORATE and operands[1] == DEC_BINDING:
            bindings[operands[0]] = operands[2]
        elif op == OP_TYPE_IMAGE:
            images[operands[0]] = {'dim': operands[2], 'arrayed': operands[4], 'ms': operands[5]}
        elif op == OP_TYPE_SAMPLED_IMAGE:
            sampled[operands[0]] = operands[1]
        elif op == OP_TYPE_POINTER:
            pointers[operands[0]] = operands[2]
        elif op == OP_VARIABLE:
            variables[operands[1]] = operands[0]
        elif op == OP_IMAGE_GATHER:
            gathers += 1
        i += count
    resources = {}
    for var, ptr_type in variables.items():
        if var not in bindings:
            continue
        pointee = pointers.get(ptr_type)
        # Uniform blocks are named on their struct type; the variable itself is often "_" or "".
        name = names.get(var) or names.get(pointee)
        if not name:
            continue
        image = images.get(sampled.get(pointee, pointee))
        resources[name] = {'binding': bindings[var], 'image': image}
    return resources, gathers


def role(resources, gathers):
    if {'u_input_texture', 'i_output_texture', 'u_fsr_data'} <= resources.keys() and gathers > 0:
        return 'Easu'
    pos, vel = resources.get('gbuffer_pos'), resources.get('gbuffer_vel')
    if pos and vel and 'u_ssr_data' in resources and 'u_gbuffer_data' in resources:
        if pos['binding'] != 3 or vel['binding'] != 4 or resources['u_gbuffer_data']['binding'] != 11 \
                or resources['u_ssr_data']['binding'] != 12:
            return None  # an interface this layer was not written for
        image = pos['image']
        if image and image['dim'] == DIM_2D and not image['ms']:
            return 'SsrSceneArray' if image['arrayed'] else 'SsrScene2D'
    return None


def main():
    target, archives = Path(sys.argv[1]), [Path(a) for a in sys.argv[2:]]
    rows, meta = [], []
    for archive in archives:
        with zipfile.ZipFile(archive) as package:
            for name in sorted(package.namelist()):
                if not name.endswith('.spv'):
                    continue
                data = package.read(name)
                resources, gathers = parse(data)
                r = role(resources, gathers)
                if r:
                    rows.append((fnv(data), len(data), r, name))
        meta.append({'archive': str(archive.resolve()), 'sha256': hashlib.sha256(archive.read_bytes()).hexdigest()})
    if not any(r[2] == 'Easu' for r in rows) or not any(r[2].startswith('Ssr') for r in rows):
        raise SystemExit('classify_shaders: no EASU or no scene SSR shader found; X-Plane update?')
    target.write_text(
        '// Generated by tools/classify_shaders.py from the installed X-Plane archives. Do not edit.\n'
        '#pragma once\n#include <cstdint>\n'
        'enum class ShaderRole : uint8_t { None, Easu, SsrScene2D, SsrSceneArray };\n'
        'struct ShaderFingerprint { uint64_t hash; uint32_t bytes; ShaderRole role; const char* name; };\n'
        'static constexpr ShaderFingerprint kShaderFingerprints[] = {\n' +
        ''.join(f'    {{UINT64_C({h}), {n}, ShaderRole::{r}, "{name}"}},\n' for h, n, r, name in rows) + '};\n')
    target.with_suffix('.json').write_text(json.dumps(
        {'archives': meta, 'shaders': [{'name': name, 'role': r, 'bytes': n, 'fnv': h} for h, n, r, name in rows]},
        indent=2) + '\n')
    print('classify_shaders: ' + ', '.join(f'{name}={r}' for _, _, r, name in rows))


if __name__ == '__main__':
    main()
